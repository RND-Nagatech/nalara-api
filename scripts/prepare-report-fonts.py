"""Derive static PDF fonts from the app's licensed variable fonts, never edit originals.

Development-only: python with fonttools installed. Production uses bundled outputs.
"""
from pathlib import Path
from shutil import copyfile
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

backend = Path(__file__).resolve().parents[1]
source = backend.parent / "flutter-apk" / "assets" / "fonts"
destination = backend / "assets" / "report-fonts"
destination.mkdir(parents=True, exist_ok=True)
for family, weight, suffix in [("Inter", 400, "Regular"), ("Inter", 600, "SemiBold"), ("Lora", 600, "SemiBold")]:
    font = TTFont(source / f"{family}-Variable.ttf")
    # Pin every variable axis so runtime font embedding needs no variation state.
    axes = {axis.axisTag: axis.defaultValue for axis in font["fvar"].axes}
    axes["wght"] = weight
    static = instantiateVariableFont(font, axes, inplace=False)
    # Derived fonts use new family names, including the source's reserved Lora
    # name. Preserve copyright/license records and copy the original OFLs.
    derived = "NalaraSerif" if family == "Lora" else "NalaraSans"
    for record in list(static["name"].names):
        if record.nameID in {1, 3, 4, 6, 16, 25}:
            value = f"{derived}-{suffix}" if record.nameID == 6 else f"{derived} {suffix}" if record.nameID in {3, 4} else derived
            static["name"].setName(value, record.nameID, record.platformID, record.platEncID, record.langID)
    static.save(destination / f"{derived}-{suffix}.ttf")
    # Remove only the exact obsolete outputs generated by the prior version.
    (destination / f"{family}-{suffix}.ttf").unlink(missing_ok=True)
for family in ["Inter", "Lora"]:
    copyfile(source / f"{family}-OFL.txt", destination / f"{family}-OFL.txt")
print("Prepared three licensed static report fonts")
